//   Kredit Foto → Photo Credits · Jadwal → Schedule · Tentang → About · item → item(s)

const plural = (n, one, many) => (Number(n) === 1 ? one : many)
const items = (n) => `${n} ${plural(n, 'item', 'items')}`
const ordinal = (n) => {
  const v = Number(n), s = v % 100
  if (s >= 11 && s <= 13) return `${v}th`
  return `${v}${{ 1: 'st', 2: 'nd', 3: 'rd' }[v % 10] || 'th'}`
}

